    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        if (servicio.getVentas().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay ventas para exportar.");
            return;
        }
        String[] opciones = {"Por Vendedores", "Por Productos"};
        int seleccion = JOptionPane.showOptionDialog(this, "¿Qué tipo de reporte desea exportar?", 
                "Tipo de Exportación", JOptionPane.DEFAULT_OPTION, JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[0]);
                
        if (seleccion == -1) return; // Si el usuario cierra la ventana
        
        JFileChooser chooser = new JFileChooser();
        chooser.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
        if (chooser.showSaveDialog(this) == JFileChooser.APPROVE_OPTION) {
            try {
                String ruta = chooser.getSelectedFile().getAbsolutePath();
                if (seleccion == 0) {
                    servicio.exportarReporteVendedores(ruta);
                } else {
                    servicio.exportarReporteProductos(ruta);
                }
                JOptionPane.showMessageDialog(this, "Exportación generada exitosamente (CSV y JSON)");
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Error al exportar: " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_btnExportarActionPerformed

