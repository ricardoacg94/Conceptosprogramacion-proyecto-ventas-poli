    private void actualizarComboVendedores() {
        String seleccionado = (String) cmbFiltroVendedor.getSelectedItem();
        cmbFiltroVendedor.removeAllItems();
        cmbFiltroVendedor.addItem("Todos");
        for (Vendedor v : servicio.getVendedores())
        {
            cmbFiltroVendedor.addItem(v.getDocumento() + " - " + v.getNombres());
        }
        if (seleccionado != null) cmbFiltroVendedor.setSelectedItem(seleccionado);
    }

    private void actualizarComboProductos()
    {
        String seleccionado = (String) cmbFiltroProducto.getSelectedItem();
        cmbFiltroProducto.removeAllItems();
        cmbFiltroProducto.addItem("Todos");
        for (Producto p : servicio.getProductos())
        {
            cmbFiltroProducto.addItem(p.getIdProducto() + " - " + p.getNombre());
        }
        if (seleccionado != null) cmbFiltroProducto.setSelectedItem(seleccionado);
    }

    private void actualizarTabla() {
        modeloTabla.setRowCount(0);
        double totalGeneral = 0;
        String fVendedor = (String) cmbFiltroVendedor.getSelectedItem();
        String fProducto = (String) cmbFiltroProducto.getSelectedItem();
        for (Venta v : servicio.getVentas())
        {
            String docStr = v.getVendedor().getDocumento() + " - " + v.getVendedor().getNombres();
            boolean matchVendedor = (fVendedor == null || fVendedor.equals("Todos") || fVendedor.equals(docStr));
            if (matchVendedor)
            {
                for (DetalleVenta dv : v.getDetalles())
                {
                    String prodStr = dv.getProducto().getIdProducto() + " - " + dv.getProducto().getNombre();
                    boolean matchProducto = (fProducto == null || fProducto.equals("Todos") || fProducto.equals(prodStr));
                    if (matchProducto)
                    {
                        Object[] fila = 
                        {
                            v.getVendedor().getNombres(), v.getVendedor().getDocumento(),
                            dv.getProducto().getNombre(), dv.getCantidad(),
                            String.format(java.util.Locale.US, "%.2f", dv.getValorUnitario()),
                            String.format(java.util.Locale.US, "%.2f", dv.getValorTotal())
                        };
                        modeloTabla.addRow(fila);
                        totalGeneral += dv.getValorTotal();
                    }
                }
            }
        }
        lblTotalGeneral.setText(String.format(java.util.Locale.US, "Total Filtrado: $%.2f", totalGeneral));
    }

